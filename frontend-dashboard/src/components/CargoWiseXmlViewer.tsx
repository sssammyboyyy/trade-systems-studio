"use client";

import React, { useEffect, useState } from "react";
import { Code2, Copy, Check, Download, Info } from "lucide-react";
import { fetchCargoWiseDiff } from "@/lib/api";
import type { CargoWiseDiff } from "@/lib/types";

interface CargoWiseXmlViewerProps {
  conceptId?: string;
}

const STATUS_STYLE: Record<string, string> = {
  READY_FOR_INGESTION: "border-status-emerald/40 text-ink-emerald",
  HELD_PENDING_REVIEW: "border-status-amber/40 text-ink-amber",
  BLOCKED_DO_NOT_TRANSMIT: "border-status-crimson/40 text-ink-crimson",
  NOT_APPLICABLE: "border-terminal-border text-ink-muted",
};

/**
 * Raw vs reconciled UniversalShipment-style XML, generated by the backend from the audit
 * result. Nothing is transmitted: there is no eAdaptor transport in this project.
 */
export const CargoWiseXmlViewer: React.FC<CargoWiseXmlViewerProps> = ({ conceptId = "concept_1_customs" }) => {
  const [viewMode, setViewMode] = useState<"reconciled" | "raw">("reconciled");
  const [copied, setCopied] = useState(false);
  const [diff, setDiff] = useState<CargoWiseDiff | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let live = true;
    setDiff(null);
    setError(null);
    fetchCargoWiseDiff(conceptId)
      .then((d) => live && setDiff(d))
      .catch(() => live && setError("XML export is generated for the bundled sample documents only."));
    return () => {
      live = false;
    };
  }, [conceptId]);

  const content = diff ? (viewMode === "reconciled" ? diff.reconciled_lawful_xml : diff.raw_unaudited_xml) : "";

  const handleCopy = () => {
    navigator.clipboard.writeText(content);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([content], { type: "application/xml" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `universal_shipment_${viewMode}_${diff?.audit_run_id ?? conceptId}.xml`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const btn = "flex items-center gap-1 rounded border border-terminal-border bg-terminal-elevated px-2.5 py-1 text-ink-secondary transition-colors hover:bg-terminal-border disabled:opacity-40";

  return (
    <div className="w-full overflow-hidden rounded-xl border border-terminal-subtle bg-terminal-slate font-mono text-xs">
      <div className="flex flex-col justify-between gap-3 border-b border-terminal-subtle p-3.5 sm:flex-row sm:items-center">
        <div className="flex flex-wrap items-center gap-2">
          <Code2 className="h-4 w-4 text-ink-cobalt" aria-hidden />
          <span className="font-bold text-ink-primary">UniversalShipment XML (v1.1 structure)</span>
          {diff && (
            <span className={`rounded border px-2 py-0.5 text-[10px] font-bold ${STATUS_STYLE[diff.status] ?? ""}`}>
              {diff.status.replace(/_/g, " ")}
            </span>
          )}
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <div className="flex rounded-lg border border-terminal-border/60 bg-terminal-elevated p-0.5" role="tablist">
            {(["reconciled", "raw"] as const).map((mode) => (
              <button
                key={mode}
                role="tab"
                aria-selected={viewMode === mode}
                onClick={() => setViewMode(mode)}
                className={`rounded px-2.5 py-1 text-[11px] font-medium transition-colors ${
                  viewMode === mode ? "bg-terminal-border text-ink-primary" : "text-ink-muted hover:text-ink-primary"
                }`}
              >
                {mode === "reconciled" ? "Reconciled" : "As extracted"}
              </button>
            ))}
          </div>
          <button onClick={handleCopy} disabled={!content} className={btn}>
            {copied ? <Check className="h-3.5 w-3.5 text-ink-emerald" /> : <Copy className="h-3.5 w-3.5" />}
            <span className="text-[11px]">{copied ? "Copied" : "Copy"}</span>
          </button>
          <button onClick={handleDownload} disabled={!content} className={btn}>
            <Download className="h-3.5 w-3.5" />
            <span className="text-[11px]">.xml</span>
          </button>
        </div>
      </div>

      {diff && diff.diff_summary.length > 0 && (
        <div className="overflow-x-auto border-b border-terminal-subtle">
          <table className="w-full text-left text-[11px]">
            <thead className="text-ink-muted">
              <tr>
                <th className="px-3 py-2 font-medium">Field</th>
                <th className="px-3 py-2 font-medium">As extracted</th>
                <th className="px-3 py-2 font-medium">Reconciled</th>
                <th className="px-3 py-2 font-medium">Basis</th>
              </tr>
            </thead>
            <tbody>
              {diff.diff_summary.map((row) => (
                <tr key={row.node} className="border-t border-terminal-subtle">
                  <td className="px-3 py-1.5 text-ink-secondary">{row.node}</td>
                  <td className="px-3 py-1.5 tabular-nums text-ink-crimson line-through decoration-1">{row.raw}</td>
                  <td className="px-3 py-1.5 tabular-nums text-ink-emerald">{row.reconciled}</td>
                  <td className="px-3 py-1.5 text-ink-muted">{row.statute}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      <pre className="max-h-[360px] overflow-auto bg-canvas-dark p-4 text-[11px] leading-relaxed text-ink-secondary">
        <code>{error ?? (diff ? content || "No shipment XML for this document type." : "Loading…")}</code>
      </pre>

      <div className="flex items-start gap-2 border-t border-terminal-subtle bg-terminal-slate p-3 text-[11px] text-ink-muted">
        <Info className="mt-0.5 h-3.5 w-3.5 shrink-0" aria-hidden />
        <span>
          Built from the audit result. Checked against an in-repo structural XSD only, not WiseTech-published schemas, and
          never transmitted: this project has no eAdaptor connection.
        </span>
      </div>
    </div>
  );
};
